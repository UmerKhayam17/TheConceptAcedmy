/**
 * Map shape expected by `moduleUtils` and `userController` (key → { name, description, actions }).
 */
function buildModulesMap() {
  const map = {};
  SYSTEM_MODULES.forEach((mod) => {
    map[mod.key] = {
      name: mod.label,
      description: mod.description,
      actions: mod.actions,
    };
  });
  return map;
}

/**
 * Payload for GET /config/system-modules (sidebar + permission UI).
 */
function getSystemModulesForApi({ forPermissions = false } = {}) {
  return [...SYSTEM_MODULES]
    .filter((mod) => !forPermissions || mod.showInPermissions !== false)
    .sort((a, b) => a.order - b.order)
    .map((mod) => ({
      key: mod.key,
      panelSlug: mod.panelSlug,
      label: mod.label,
      icon: mod.icon,
      description: mod.description,
      actions: mod.actions,
      order: mod.order,
      parentGroup: mod.parentGroup || null,
      showInPermissions: mod.showInPermissions !== false,
    }));
}

